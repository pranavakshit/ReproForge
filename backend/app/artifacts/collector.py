"""Artifact collection, classification, and cataloging."""

import hashlib
import io
import os
import shutil
import subprocess
import tarfile
from pathlib import Path
from typing import List, Optional

from backend.app.core.config import settings
from backend.app.core.logging import get_logger
from backend.app.schemas.entities import ArtifactItemCreate

logger = get_logger("reproforge.artifacts.collector")


def compute_sha256(file_path: Path, block_size: int = 65536) -> str:
    """Compute cryptographic SHA-256 digest of a file in streaming chunks."""
    hasher = hashlib.sha256()
    with open(file_path, "rb") as fp:
        while chunk := fp.read(block_size):
            hasher.update(chunk)
    return hasher.hexdigest()


class ArtifactCollector:
    """Discovers, packages, hashes, and stores build artifacts."""

    def __init__(self, base_artifacts_dir: Optional[Path] = None) -> None:
        self.base_dir = base_artifacts_dir or settings.ARTIFACTS_DIR
        self.base_dir.mkdir(parents=True, exist_ok=True)

    def collect_from_workspace(
        self,
        build_id: str,
        workspace_source_dir: Path,
        docker_image_tag: Optional[str] = None,
        bundle_workspace_if_empty: bool = False,
    ) -> List[ArtifactItemCreate]:
        """Collect all relevant artifacts generated by the build."""
        dest_dir = self.base_dir / build_id
        dest_dir.mkdir(parents=True, exist_ok=True)

        collected: List[ArtifactItemCreate] = []

        # 1. Collect Docker Image if built
        if docker_image_tag:
            image_tar = dest_dir / f"docker_image_{build_id}.tar"
            logger.info(f"[{build_id}] Exporting Docker image {docker_image_tag} to {image_tar}...")
            try:
                subprocess.run(
                    ["docker", "save", docker_image_tag, "-o", str(image_tar)],
                    stdin=subprocess.DEVNULL,
                    check=True,
                    capture_output=True,
                )
                if image_tar.exists():
                    sha = compute_sha256(image_tar)
                    collected.append(
                        ArtifactItemCreate(
                            build_execution_id=build_id,
                            relative_path=image_tar.name,
                            artifact_type="docker_oci_image_tar",
                            file_size_bytes=image_tar.stat().st_size,
                            strict_sha256=sha,
                            metadata_json={"image_tag": docker_image_tag},
                        )
                    )
            except Exception as e:
                logger.error(f"[{build_id}] Failed to export Docker image: {e}")

        # 2. Check for Python dist/ directory
        dist_dir = workspace_source_dir / "dist"
        if dist_dir.exists() and dist_dir.is_dir():
            for item in dist_dir.iterdir():
                if item.is_file() and (item.name.endswith(".whl") or item.name.endswith(".tar.gz")):
                    target_file = dest_dir / item.name
                    shutil.copy2(item, target_file)
                    sha = compute_sha256(target_file)
                    artifact_type = "python_wheel" if item.name.endswith(".whl") else "python_sdist"
                    collected.append(
                        ArtifactItemCreate(
                            build_execution_id=build_id,
                            relative_path=item.name,
                            artifact_type=artifact_type,
                            file_size_bytes=target_file.stat().st_size,
                            strict_sha256=sha,
                            metadata_json={"original_name": item.name},
                        )
                    )

        # 3. Check for standalone archives (.tar, .tar.gz, .zip) directly in workspace
        for item in workspace_source_dir.glob("*.zip"):
            if item.is_file():
                target_file = dest_dir / item.name
                shutil.copy2(item, target_file)
                sha = compute_sha256(target_file)
                collected.append(
                    ArtifactItemCreate(
                        build_execution_id=build_id,
                        relative_path=item.name,
                        artifact_type="zip_archive",
                        file_size_bytes=target_file.stat().st_size,
                        strict_sha256=sha,
                    )
                )

        for item in workspace_source_dir.glob("*.tar*"):
            if item.is_file():
                target_file = dest_dir / item.name
                shutil.copy2(item, target_file)
                sha = compute_sha256(target_file)
                collected.append(
                    ArtifactItemCreate(
                        build_execution_id=build_id,
                        relative_path=item.name,
                        artifact_type="tar_archive",
                        file_size_bytes=target_file.stat().st_size,
                        strict_sha256=sha,
                    )
                )

        if not collected and bundle_workspace_if_empty:
            bundle_path = dest_dir / f"build_bundle_{build_id}.tar"
            entries = sorted(
                [
                    p
                    for p in workspace_source_dir.rglob("*")
                    if p.is_file() and ".git" not in p.parts and ".venv" not in p.parts
                ],
                key=lambda p: p.relative_to(workspace_source_dir).as_posix(),
            )
            if entries:
                with tarfile.open(bundle_path, "w") as tf:
                    for item in entries:
                        rel = item.relative_to(workspace_source_dir).as_posix()
                        st = item.stat()
                        ti = tarfile.TarInfo(name=rel)
                        ti.size = st.st_size
                        ti.mtime = int(st.st_mtime)
                        ti.mode = st.st_mode & 0o777
                        with open(item, "rb") as fp:
                            tf.addfile(ti, fp)
                sha = compute_sha256(bundle_path)
                collected.append(
                    ArtifactItemCreate(
                        build_execution_id=build_id,
                        relative_path=bundle_path.name,
                        artifact_type="tar_archive",
                        file_size_bytes=bundle_path.stat().st_size,
                        strict_sha256=sha,
                        metadata_json={"bundled_files": len(entries)},
                    )
                )

        logger.info(f"[{build_id}] Collected {len(collected)} artifact(s).")
        return collected
